"""Process-creation audit: can the machine name who started a program (R9: who ran powercfg.exe before a cut)?

    fieldkit power audit [--write-fix] [--callers powercfg.exe [--since YYYY-MM-DD]] [--json]

Checks (Windows; elsewhere "not-this-platform"), none needs admin:
  cmdline    HKLM ...\\Audit ProcessCreationIncludeCmdLine_Enabled = 1 (command lines in the records)
  readable   this session can read the Security log (Administrators or Event Log Readers in the TOKEN: after a new logon)
  group      the account is a member of Event Log Readers (may not be in the token yet: sign out and in)
  events     Security 4688 records exist (proves "Process Creation" auditing is on)
The missing admin steps (audit policy, command-line flag, group) are written as ONE self-elevating script
(state/power/enable-process-audit.ps1): one UAC prompt, no typing. A model never runs it: it is a security setting.
--callers reads 4688 and prints, per start of PROCESS, the creator process and the command line.
"""
import json
import re
import subprocess
import sys
import time
from pathlib import Path

FLAG_KEY = r"HKLM\SOFTWARE\Microsoft\Windows\CurrentVersion\Policies\System\Audit"
STEPS = {
    "audit": 'auditpol.exe /set /subcategory:"Process Creation" /success:enable',
    "cmdline": 'reg.exe add "%s" /v ProcessCreationIncludeCmdLine_Enabled /t REG_DWORD /d 1 /f' % FLAG_KEY,
    "group": 'net.exe localgroup "Event Log Readers" $env:USERNAME /add',
}

PROBE = r"""
$ErrorActionPreference='SilentlyContinue'
$o=@{}
$o.cmdline=[int](Get-ItemProperty 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Policies\System\Audit').ProcessCreationIncludeCmdLine_Enabled
$o.group=[bool]((net localgroup 'Event Log Readers') -match ('(?i)\b'+[regex]::Escape($env:USERNAME)+'$'))
try{ Get-WinEvent -LogName Security -MaxEvents 1 -ErrorAction Stop | Out-Null; $o.readable=$true }catch{ $o.readable=$false }   # a filtered query reports "unauthorized" as "no events", so read unfiltered
$o.events=$false
if($o.readable){ $o.events=[bool](Get-WinEvent -FilterHashtable @{LogName='Security';Id=4688} -MaxEvents 1 -ErrorAction SilentlyContinue) }
$o | ConvertTo-Json -Compress
"""

CALLERS = r"""
$ErrorActionPreference='Stop'
$s=[datetime]::Parse('%SINCE%')
Get-WinEvent -FilterHashtable @{LogName='Security';Id=4688;StartTime=$s} | %{
  $x=[xml]$_.ToXml(); $d=@{}; foreach($n in $x.Event.EventData.Data){$d[$n.Name]=[string]$n.'#text'}
  if((Split-Path $d.NewProcessName -Leaf) -ieq '%PROC%'){ [pscustomobject]@{t=$_.TimeCreated.ToUniversalTime().ToString('o');creator=$d.ParentProcessName;pid=$d.NewProcessId;cmd=$d.CommandLine} }
} | ConvertTo-Json -Compress
"""


def probe(run=subprocess.run):
    if sys.platform != "win32":
        return {"status": "not-this-platform"}
    r = run(["powershell", "-NoProfile", "-NonInteractive", "-Command", PROBE], capture_output=True, text=True, timeout=60)
    try:
        j = json.loads(r.stdout)
    except ValueError:
        return {"status": "error", "error": (r.stderr or r.stdout)[:200]}
    j["status"] = "ok"
    return j


def verdict(p):
    """Pure: probe result -> (PASS | SIGN-OUT | FAIL | error | not-this-platform, admin steps still needed)."""
    if p.get("status") == "not-this-platform":
        return "not-this-platform", []
    if p.get("status") != "ok":
        return "error", []
    need = []
    if not p.get("events") and p.get("readable"):
        need.append("audit")              # readable and no 4688 record: auditing is off
    if p.get("cmdline") != 1:
        need.append("cmdline")
    if not p.get("readable") and not p.get("group"):
        need.append("group")
    if not p.get("readable") and p.get("group") and not need:
        return "SIGN-OUT", []             # member, but the token predates it: one new logon
    if not p.get("readable") and "audit" not in need and not p.get("events"):
        need.insert(0, "audit")           # unreadable: auditing cannot be seen, so it is set (harmless when already on)
    if need:
        return "FAIL", need
    return "PASS", []


def fix_script(steps):
    """The one self-elevating script for the missing steps."""
    body = "\n".join(STEPS[s] for s in steps)
    return ("# generated by fieldkit power audit --write-fix; one UAC prompt\n"
            "if(-not ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole('Administrators')){\n"
            "  Start-Process powershell -Verb RunAs -ArgumentList '-NoProfile','-ExecutionPolicy','Bypass','-File',$PSCommandPath; exit }\n"
            "$env:USERNAME | Out-Null\n"
            + body + "\nauditpol.exe /get /subcategory:\"Process Creation\"\nRead-Host 'Done. Sign out and in once, then press Enter'\n")


def callers(proc, since, run=subprocess.run):
    s = CALLERS.replace("%SINCE%", time.strftime("%Y-%m-%d", time.localtime(since))).replace("%PROC%", proc)
    r = run(["powershell", "-NoProfile", "-NonInteractive", "-Command", s], capture_output=True, text=True, timeout=300)
    if not r.stdout.strip():
        return {"rows": [], "error": (r.stderr or "no 4688 records for " + proc)[:200]}
    j = json.loads(r.stdout)
    return {"rows": [j] if isinstance(j, dict) else j}


def run_cmd(write_fix=False, proc=None, since=None, as_json=False, out=print, state_dir=None, runner=subprocess.run):
    p = probe(runner)
    v, need = verdict(p)
    res = {"verdict": v, "probe": p, "missing": need}
    if write_fix and need:
        d = Path(state_dir or Path(__file__).resolve().parents[2] / "state" / "power")
        d.mkdir(parents=True, exist_ok=True)
        f = d / "enable-process-audit.ps1"
        f.write_text(fix_script(need), encoding="utf-8")
        res["fix_script"] = str(f)
    if proc and v == "PASS":
        from .incidents import parse_since
        res["callers"] = callers(proc, parse_since(since), runner)
    if as_json:
        out(json.dumps(res, indent=1))
    else:
        out("process-creation audit: %s (%s)" % (v, ", ".join("%s=%s" % kv for kv in sorted(p.items()) if kv[0] != "status")))
        for s in need:
            out("  missing: " + s)
        if res.get("fix_script"):
            out("  one UAC: powershell -File \"%s\"" % res["fix_script"])
        for r in res.get("callers", {}).get("rows", []):
            out("  %s  %s  <- %s" % (r["t"], re.sub(r"\s+", " ", r.get("cmd") or "")[:100], r.get("creator")))
        if proc and v != "PASS":
            out("  --callers needs PASS first")
        out("NEXT: " + {"PASS": "fieldkit power audit --callers powercfg.exe", "SIGN-OUT": "sign out and in once, then re-run",
                        "FAIL": "fieldkit power audit --write-fix, then run the script it names",
                        "not-this-platform": "nothing to do"}.get(v, "see the error"))
    return 0 if v in ("PASS", "not-this-platform") else 3
