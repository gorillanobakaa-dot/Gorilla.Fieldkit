# Version: 1.0.0 · updated 26-10-26-17-30
"""A git merge driver for the files every new card touches, so two branches that each add a card merge cleanly.

    fieldkit merge-driver check            is the driver installed in this clone, and does .gitattributes name it?
    fieldkit merge-driver install          write it into this clone's git config (shared by its worktrees)
    python fieldkit/method/mergedriver.py merge %O %A %B %P      what git runs (standard library only)

2026-10-26: every PR that added a tool card conflicted in fieldkit/desk/platform_index.json and at the end of
fieldkit/desk/tools.yaml, and each hand resolution cost a full pre-commit suite (~25 min; test-parity #122 twice in
one day). Both files are lists of independent entries; a conflict between two NEW entries is not a real conflict.

  platform_index.json   (generated by `python -m fieldkit.core.platform_gate --write`) merged as data, key by key,
                        and written in the generator's own format. Git hands a driver only the three versions of ONE
                        file, so it cannot run the generator on the merged tools.yaml; the key-level merge gives the
                        same index whenever the cards merged cleanly, and tests/test_platform_gate.py (the suite and
                        CI) still fails if it ever does not: the guard stays the generator, never this driver.
  tools.yaml            cards (`- id: X` blocks) merged by id: both sides' new cards kept, each in its place.
  docs/groups.yaml      documentation groups (`  - name: X` blocks), the same way.

For the YAML files git's own line merge runs first and wins when it is clean. Only when it conflicts are the files
cut into blocks (a block = its start line, its body, and the comment lines just above it), and merged block by block:
taken from the side that changed it, added from either side. Two sides changing the SAME block differently, the same
id added twice with different text, a duplicate id, or a result that no longer parses: the normal conflict markers,
exactly as without the driver. Fail closed: the driver never guesses between two edits of one card.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

DRIVER = "fieldkit-generated"
# path in the repository -> how it is merged. .gitattributes names the same paths (test_mergedriver checks both).
FILES = {
    "fieldkit/desk/platform_index.json": "index",
    "fieldkit/desk/tools.yaml": "cards",
    "docs/groups.yaml": "groups",
}
STARTS = {"cards": re.compile(r"^- id:\s*(\S+)"), "groups": re.compile(r"^  - name:\s*(\S+)")}
SCRIPT = "fieldkit/method/mergedriver.py"


class Conflict(Exception):
    """The two sides changed the same thing differently: leave it to git's conflict markers."""


# -- the three-way rule ------------------------------------------------------------------------------------------------
def pick(base, ours, theirs):
    """One value, three versions (None = absent). The side that changed wins; both changing differently is a conflict."""
    if ours == theirs:
        return ours
    if ours == base:
        return theirs
    if theirs == base:
        return ours
    raise Conflict


# -- platform_index.json -----------------------------------------------------------------------------------------------
def _set3(base, ours, theirs):
    """A sorted list merged as a set: kept unless one side removed it, added when either side added it."""
    b, o, t = set(base or []), set(ours or []), set(theirs or [])
    return sorted((o & t) | (o - b) | (t - b))


def merge_index(base, ours, theirs):
    """{command: {platforms, why, ids}} merged key by key; a row both sides changed is merged field by field
    (platforms and ids as sets, why from the side that changed it)."""
    out = {}
    for key in sorted(set(base) | set(ours) | set(theirs)):
        b, o, t = base.get(key), ours.get(key), theirs.get(key)
        try:
            row = pick(b, o, t)
        except Conflict:
            if o is None or t is None:          # one side removed the command, the other changed it
                raise
            b = b or {}
            why = pick(b.get("why"), o.get("why"), t.get("why"))
            row = {"platforms": _set3(b.get("platforms"), o.get("platforms"), t.get("platforms")),
                   "why": why, "ids": _set3(b.get("ids"), o.get("ids"), t.get("ids"))}
        if row is not None:
            out[key] = row
    return out


def dump_index(idx):
    """Byte for byte what platform_gate.write() writes."""
    return json.dumps(idx, indent=1, ensure_ascii=False) + "\n"


# -- tools.yaml / groups.yaml ------------------------------------------------------------------------------------------
def _loose(line):
    s = line.strip()
    return not s or s.startswith("#")


def blocks(text, start):
    """text -> (preamble, [(id, block text)], epilogue); "".join of them is the text again, byte for byte."""
    lines = text.splitlines(keepends=True)
    heads = [i for i, ln in enumerate(lines) if start.match(ln)]
    if not heads:
        return text, [], ""

    def peel(lo, hi):                           # the comment/blank lines just above line hi belong to the next block
        while hi > lo and _loose(lines[hi - 1]):
            hi -= 1
        return hi

    cuts = [peel(0 if n == 0 else heads[n - 1] + 1, h) for n, h in enumerate(heads)]
    end = peel(heads[-1] + 1, len(lines))
    out, seen = [], set()
    for n, c in enumerate(cuts):
        key = start.match(lines[heads[n]]).group(1)
        if key in seen:
            raise Conflict                      # a duplicate id: nothing to key on
        seen.add(key)
        out.append((key, "".join(lines[c:cuts[n + 1] if n + 1 < len(cuts) else end])))
    return "".join(lines[:cuts[0]]), out, "".join(lines[end:])


def merge_blocks(base, ours, theirs, start):
    pb, bb, eb = blocks(base, start)
    po, bo, eo = blocks(ours, start)
    pt, bt, et = blocks(theirs, start)
    B, O, T = dict(bb), dict(bo), dict(bt)
    merged = {}
    for key in set(B) | set(O) | set(T):
        v = pick(B.get(key), O.get(key), T.get(key))
        if v is not None:
            merged[key] = v
    order = [k for k, _ in bo if k in merged]
    theirs_order = [k for k, _ in bt]
    for n, key in enumerate(theirs_order):
        if key in order or key not in merged:
            continue
        # after the block that comes before it on their side, and after any of OUR new blocks that follow that one
        prev = next((k for k in reversed(theirs_order[:n]) if k in order), None)
        at = 0 if prev is None else order.index(prev) + 1
        while at < len(order) and order[at] not in B and order[at] not in T:
            at += 1
        order.insert(at, key)
    return pick(pb, po, pt) + "".join(merged[k] for k in order) + pick(eb, eo, et)


def _parses(text, kind):
    """The merged YAML still loads and holds every block once (skipped when PyYAML is not installed)."""
    try:
        import yaml
    except ImportError:
        return True
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError:
        return False
    rows = (data or {}).get("tools" if kind == "cards" else "groups") or []
    keys = [r.get("id" if kind == "cards" else "name") for r in rows if isinstance(r, dict)]
    return len(keys) == len(set(keys)) == len(blocks(text, STARTS[kind])[1])


# -- what git runs -----------------------------------------------------------------------------------------------------
def _read(p):
    return Path(p).read_bytes().decode("utf-8")


def _line_merge(o, a, b):
    """git's own merge with conflict markers, into a; -> number of conflicts (0 clean, <0 error)."""
    return subprocess.run(["git", "merge-file", "-L", "ours", "-L", "base", "-L", "theirs", a, o, b],
                          capture_output=True).returncode


def merge(o, a, b, path):
    """-> 0 merged into a, 1 conflict markers in a (git then reports a conflict, as without the driver)."""
    kind = FILES.get(str(path).replace("\\", "/"))
    try:
        base, ours, theirs = _read(o), _read(a), _read(b)
        if kind == "index":
            text = dump_index(merge_index(json.loads(base or "{}"), json.loads(ours or "{}"),
                                          json.loads(theirs or "{}")))
        elif kind in STARTS:
            # git's line merge first: a clean one is what git would have done anyway
            saved = Path(a).read_bytes()
            if _line_merge(o, a, b) == 0:
                return 0
            Path(a).write_bytes(saved)
            text = merge_blocks(base, ours, theirs, STARTS[kind])
            if not _parses(text, kind):
                raise Conflict
        else:
            raise Conflict
    except (Conflict, ValueError, UnicodeDecodeError, AttributeError):
        return 1 if _line_merge(o, a, b) != 0 else 0
    Path(a).write_bytes(text.encode("utf-8"))
    sys.stderr.write(f"fieldkit merge-driver: {path} merged entry by entry\n")
    return 0


# -- install and check -------------------------------------------------------------------------------------------------
def interpreter():
    """The base Python, never a checkout's .venv: a worktree's venv is removed with the worktree, and git config is
    shared by every worktree of the clone. Forward slashes: git runs the driver through sh, on Windows too."""
    py = getattr(sys, "_base_executable", None) or sys.executable
    return str(Path(py)).replace("\\", "/")


def command(copy, py=None):
    """The driver line: the checkout's own script, else the clone's copy (a branch cut before the driver existed),
    else git's own line merge."""
    py = py or interpreter()
    return (f'f={SCRIPT}; [ -f "$f" ] || f="{copy}"; if [ -f "$f" ]; then "{py}" "$f" merge %O %A %B %P; '
            f'else git merge-file -L ours -L base -L theirs %A %O %B; fi')


def _git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True)


def common_dir(repo):
    """The clone's shared git folder (every worktree of the clone reads its config and info/attributes)."""
    r = _git(repo, "rev-parse", "--path-format=absolute", "--git-common-dir")
    return Path(r.stdout.strip()) if r.returncode == 0 and r.stdout.strip() else None


def _attr_lines():
    return [f"{p} merge={DRIVER}" for p in FILES]


def attributes_ok(repo):
    """-> the FILES paths neither .gitattributes nor the clone's info/attributes sends to the driver."""
    named = set()
    cd = common_dir(repo)
    for f in [Path(repo) / ".gitattributes"] + ([cd / "info" / "attributes"] if cd else []):
        try:
            text = f.read_text(encoding="utf-8")
        except OSError:
            continue
        named |= {ln.split()[0] for ln in text.splitlines() if f"merge={DRIVER}" in ln.split()[1:]}
    return [p for p in FILES if p not in named]


def check(repo="."):
    have = _git(repo, "config", "--get", f"merge.{DRIVER}.driver").stdout.strip()
    missing = attributes_ok(repo)
    ok = bool(have) and SCRIPT in have and not missing
    if not have:
        why = "not installed: fieldkit merge-driver install"
    elif SCRIPT not in have:
        why = f"merge.{DRIVER}.driver is not this driver: {have[:120]}"
    elif missing:
        why = ".gitattributes does not send these to the driver: " + ", ".join(missing)
    else:
        why = "installed; .gitattributes sends " + ", ".join(FILES) + " to it"
    return {"ok": ok, "driver": have, "why": why}


def install(repo=".", py=None):
    """Idempotent. Writes only inside the clone's git folder: two config keys, a copy of this script, and the paths in
    info/attributes, so branches cut before .gitattributes named the driver merge main cleanly the first time too."""
    cd = common_dir(repo)
    if cd is None:
        return {"ok": False, "why": f"{repo} is not a git checkout"}
    changed = False
    copy = cd / "fieldkit-mergedriver.py"
    me = Path(__file__).read_bytes()
    if not copy.is_file() or copy.read_bytes() != me:
        copy.write_bytes(me)
        changed = True
    attrs = cd / "info" / "attributes"
    try:
        old = attrs.read_text(encoding="utf-8")
    except OSError:
        old = ""
    add = [ln for ln in _attr_lines() if ln not in old.splitlines()]
    if add:
        attrs.parent.mkdir(parents=True, exist_ok=True)
        attrs.write_text(old + ("" if not old or old.endswith("\n") else "\n") + "\n".join(add) + "\n",
                         encoding="utf-8", newline="\n")
        changed = True
    want = command(str(copy).replace("\\", "/"), py)
    if _git(repo, "config", "--get", f"merge.{DRIVER}.driver").stdout.strip() != want:
        r = _git(repo, "config", f"merge.{DRIVER}.driver", want)
        if r.returncode != 0:
            return {"ok": False, "why": "git config failed: " + r.stderr.strip()[:200]}
        _git(repo, "config", f"merge.{DRIVER}.name", "Fieldkit cards and generated indexes, merged entry by entry")
        changed = True
    return dict(check(repo), changed=changed)


def main(argv=None, prog="fieldkit merge-driver"):
    argv = list(sys.argv[1:] if argv is None else argv)
    if any(a in ("-h", "--help") for a in argv):
        print(f"usage: {prog} [check|install] [--json] [--quiet]\n" + __doc__)
        raise SystemExit(0)                     # as argparse does: every method's --help exits 0
    if argv[:1] == ["merge"] and len(argv) == 5:
        return merge(*argv[1:])
    if argv[:1] in (["check"], ["install"], []):
        quiet = "--quiet" in argv
        r = install() if argv[:1] == ["install"] else check()
        if "--json" in argv:
            print(json.dumps(r, indent=1))
        elif not (quiet and r["ok"] and not r.get("changed")):
            print(("ok  " if r["ok"] else "NEEDS  ") + r["why"] + (" (written now)" if r.get("changed") else ""))
        return 0 if r["ok"] else 3
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
